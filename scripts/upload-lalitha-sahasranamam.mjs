function stripMarker(line) {
  // trailing "|| N ||" (ASCII) or "॥ N ॥" (Devanagari danda, Latin/Devanagari digits)
  return line.replace(/\s*(\|\||॥)\s*[\d०-९౦-౯]+\s*(\|\||॥)\s*$/, '').trim();
}

function markerNumber(line) {
  const m = line.match(/(\|\||॥)\s*([\d०-९౦-౯]+)\s*(\|\||॥)\s*$/);
  if (!m) return null;
  const digits = m[2];
  const devMap = '०१२३४५६७८९';
  const teMap = '౦౧౨౩౪౫౬౭౮౯';
  let out = '';
  for (const ch of digits) {
    if (/[0-9]/.test(ch)) out += ch;
    else if (devMap.includes(ch)) out += devMap.indexOf(ch);
    else if (teMap.includes(ch)) out += teMap.indexOf(ch);
    else return null;
  }
  return parseInt(out, 10);
}

function splitPadas(strippedLine) {
  return strippedLine.split(/[|।]/).map(s => s.trim()).filter(Boolean);
}

