const SLUGS_OWNED = new Set([
  'sai-chalisa', 'hanuman-chalisa', 'ganesh-chalisa', 'sudarshana-kavacham',
  'subrahmanya-sahasranamam', 'kanakadhara-stotram', 'narasimha-kavacham',
  'vishnu-sahasranamam',
]);

async function main() {
  // Safety: every update must target a slug we own.
  for (const u of UPDATES) {
    if (!SLUGS_OWNED.has(u.slug)) {
      throw new Error(`Refusing to proceed: update references out-of-scope slug "${u.slug}"`);
    }
  }

  const { headers, rows, col } = await getTabWithHeaders('shloka_stanzas');
  const slugCol = col('shloka_slug');
  const stanzaCol = col('stanza_number');
  const langCols = {
    en: col('meaning_en'),
    te: col('meaning_te'),
    ta: col('meaning_ta'),
    hi: col('meaning_hi'),
  };

  // Build an index: "slug|stanza" -> row index (0-based within `rows`)
  const rowIndex = new Map();
  rows.forEach((row, i) => {
    const key = `${row[slugCol]}|${row[stanzaCol]}`;
    rowIndex.set(key, i);
  });

  const bySlug = new Map();
  let totalApplied = 0;
  let totalSkipped = 0;
  const writes = [];

  for (const u of UPDATES) {
    if (!bySlug.has(u.slug)) bySlug.set(u.slug, []);
    const key = `${u.slug}|${u.stanza}`;
    const rIdx = rowIndex.get(key);
    if (rIdx === undefined) {
      bySlug.get(u.slug).push({ ...u, status: 'ROW NOT FOUND' });
      totalSkipped++;
      continue;
    }
    const sheetRowNumber = rIdx + 2; // +1 header row, +1 for 1-based indexing
    const colIdx = langCols[u.lang];
    const liveText = rows[rIdx][colIdx] ?? '';

    if (liveText !== u.oldText) {
      bySlug.get(u.slug).push({
        ...u, status: 'SKIPPED (live text differs from draft baseline)', liveText,
      });
      totalSkipped++;
      continue;
    }

    bySlug.get(u.slug).push({ ...u, status: 'OK', sheetRowNumber });
    totalApplied++;
    writes.push({
      range: `shloka_stanzas!${colLetter(colIdx)}${sheetRowNumber}`,
      values: [[u.newText]],
    });
  }

  // ---- Report ----
  for (const [slug, items] of bySlug.entries()) {
    console.log(`\n=== ${slug} (${items.length} cell updates) ===`);
    for (const it of items) {
      console.log(`\n[stanza ${it.stanza} / ${it.lang}] ${it.status}`);
      console.log(`  OLD: ${it.oldText}`);
      console.log(`  NEW: ${it.newText}`);
      if (it.liveText !== undefined) {
        console.log(`  LIVE (does not match draft baseline): ${it.liveText}`);
      }
    }
  }

  console.log(`\n\n=== SUMMARY ===`);
  for (const [slug, items] of bySlug.entries()) {
    const ok = items.filter((i) => i.status === 'OK').length;
    const skipped = items.length - ok;
    console.log(`${slug}: ${ok} cell(s) to update, ${skipped} skipped`);
  }
  console.log(`\nTotal cells to update: ${totalApplied}`);
  console.log(`Total skipped: ${totalSkipped}`);

  if (!WRITE) {
    console.log('\nDRY RUN — no changes written. Pass --write to apply.');
    return;
  }

  console.log(`\nWriting ${writes.length} cell(s) to the live Sheet...`);
  const sheets = await getSheetsClient();
  for (const w of writes) {
    await sheets.spreadsheets.values.update({
      spreadsheetId: SPREADSHEET_ID,
      range: w.range,
      valueInputOption: 'RAW',
      requestBody: { values: w.values },
    });
    console.log(`  wrote ${w.range}`);
  }
  console.log('Done.');
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
