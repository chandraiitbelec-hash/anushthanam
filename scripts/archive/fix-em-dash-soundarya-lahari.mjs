const LANG_COLS = ['en', 'te', 'ta', 'hi'];

async function main() {
  const { rows, col } = await getTabWithHeaders('shloka_stanzas');
  const cSlug = col('shloka_slug');
  const cStanza = col('stanza_number');
  const colByLang = {
    en: col('meaning_en'),
    te: col('meaning_te'),
    ta: col('meaning_ta'),
    hi: col('meaning_hi'),
  };

  let cellsChanged = 0;
  let cellsSkippedMismatch = 0;
  const writeTargets = [];

  const sheetRows = Object.keys(FIXES).map(Number).sort((a, b) => a - b);

  for (const sheetRow of sheetRows) {
    const rowIdx = sheetRow - 2; // undo +1 header, +1 1-based used when building FIXES
    const liveRow = rows[rowIdx];
    if (!liveRow || liveRow[cSlug] !== SLUG) {
      console.log(`\n[WARN] Row ${sheetRow}: live row no longer matches shloka_slug="${SLUG}" (found "${liveRow ? liveRow[cSlug] : '<missing row>'}"). Skipping.`);
      continue;
    }
    const stanza = liveRow[cStanza];
    console.log(`\n--- Stanza ${stanza} (sheet row ${sheetRow}) ---`);

    for (const lang of LANG_COLS) {
      const fix = FIXES[sheetRow][lang];
      if (!fix) continue;
      const liveText = liveRow[colByLang[lang]] || '';
      if (liveText !== fix.old) {
        console.log(`  [${lang}] SKIP -- live cell text no longer matches expected 'old' text (sheet may have changed since this script was drafted).`);
        console.log(`    Expected old: ${fix.old}`);
        console.log(`    Live text:    ${liveText}`);
        cellsSkippedMismatch++;
        continue;
      }
      console.log(`  [${lang}] OLD: ${fix.old}`);
      console.log(`  [${lang}] NEW: ${fix.new}`);
      cellsChanged++;
      writeTargets.push({
        range: `shloka_stanzas!${colLetter(colByLang[lang])}${sheetRow}`,
        value: fix.new,
      });
    }
  }

  console.log(`\n=== Summary ===`);
  console.log(`Row-fix entries defined: ${sheetRows.length}`);
  console.log(`Cells that would change: ${cellsChanged}`);
  console.log(`Cells skipped (live text mismatch): ${cellsSkippedMismatch}`);

  if (!WRITE) {
    console.log('\nDry run only -- no changes written. Re-run with --write to apply (Phase 2, after human review).');
    return;
  }

  if (writeTargets.length === 0) {
    console.log('\nNothing to write.');
    return;
  }

  const sheets = await getSheetsClient();
  await sheets.spreadsheets.values.batchUpdate({
    spreadsheetId: SPREADSHEET_ID,
    requestBody: {
      valueInputOption: 'RAW',
      data: writeTargets.map(t => ({ range: t.range, values: [[t.value]] })),
    },
  });
  console.log(`\nWrote ${writeTargets.length} cells.`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
