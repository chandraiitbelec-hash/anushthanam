async function run() {
  const existing = await getExistingSlugs();
  const toAdd = shlokas.filter(s => !existing.has(s.slug));

  if (toAdd.length === 0) {
    console.log('All shlokas already exist — nothing to add.');
    return;
  }

  const rows = toAdd.map(s => [
    s.slug,
    s.title_en,
    s.title_te,
    s.title_ta,
    s.title_hi,
    s.type,
    s.deity_slug,
    s.brief_intro_en,
    s.brief_intro_te,
    s.brief_intro_ta,
    s.brief_intro_hi,
    s.language_of_composition,
    s.stanza_count,
    s.source_text,
    s.status,
  ]);

  await sheets.spreadsheets.values.append({
    spreadsheetId: SPREADSHEET_ID,
    range: `${SHEET}!A1`,
    valueInputOption: 'RAW',
    requestBody: { values: rows },
  });

  console.log(`Added ${toAdd.length} shlokas:`);
  toAdd.forEach(s => console.log(`  ✓ ${s.slug}`));
}

run().catch(err => { console.error(err); process.exit(1); });
